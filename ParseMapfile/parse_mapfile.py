class ContributionType(str, Enum):
    """Kinds of contributions found in the firmware report."""

    BSS = "bss"
    CODE = "code"
    DATA = "data"
    DEBUG = "debug"
    OTHER = "other"
    RODATA = "rodata"

class ContributionComponent(str, Enum):
    """The subcomponent the contribution comes from"""
    LIBTOMMATH = "LibTomMath"
    TOMSFASTMATH = "TomsFastMath"
    LIBTOMCRYPT = "LibTomCrypt"
    IBMSWTPM = "ibmswtpm2"
    STM32 = "STM32"
    LIBC = "LIBC"

    OTHER = "other"




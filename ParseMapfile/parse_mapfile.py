"""Utilities for loading and summarizing firmware linker-map JSON reports.

The JSON payload generated by the report tool contains memory-region data,
contribution records, linker metadata, and section statistics. This module exposes
helpers to load the report and inspect common fields without needing to manually
navigate the raw dictionary structure.
"""


@dataclass(frozen=True)
class Contribution:
    """A single contribution entry from the report's contributions list."""

    section: str
    address: int
    size: int
    source: str
    symbol: str
    kind: ContributionType
    component: ContributionComponent
    line_no: int | None
    local_stack: int | None
    max_stack: int | None
    raw: dict[str, Any] = field(repr=False)

    @classmethod
    def _get_component(cls, source : str) -> ContributionComponent:

        if "/STM32TPM/App/" in source:
            return ContributionComponent.IBMSWTPM
        if "liblibtomcrypt.a" in source:
            return ContributionComponent.LIBTOMCRYPT
        if "tomsfastmath/libtfm.a" in source:
            return ContributionComponent.TOMSFASTMATH
        if "libtommath/liblibtommath.a" in source:
            return ContributionComponent.LIBTOMMATH
        if "/STM32TPM/Drivers/" in source or "/STM32TPM/Middlewares/" in source:
            return ContributionComponent.STM32
        if "/FATFS/" in source or "/Core/" in source:
            return ContributionComponent.STM32
        if "/Common/Src/" in source:
            return ContributionComponent.STM32
        if "libg_nano.a" in source or "libgcc.a" in source or "crtbegin.o" in source:
            return ContributionComponent.LIBC
        if "crti.o" in source or "crtn.o" in source:
            return ContributionComponent.LIBC

        #print(f"Other: {source}")

        return ContributionComponent.OTHER

    @classmethod
    def from_dict(cls, payload: dict[str, Any]) -> "Contribution":
        return cls(
            section=str(payload.get("section", "")),
            address=int(payload.get("address", 0) or 0),
            size=int(payload.get("size", 0) or 0),
            source=str(payload.get("source", "")),
            symbol=str(payload.get("symbol", "")),
            kind=ContributionType(payload["kind"]),
            component=Contribution._get_component(payload.get("source", "")),
            line_no=payload.get("line_no"),
            local_stack=payload.get("local_stack"),
            max_stack=payload.get("max_stack"),
            raw=payload,
        )

@dataclass
class FirmwareReport:
    """Typed wrapper around the firmware report JSON payload."""

    path: Path
    payload: dict[str, Any]

    @classmethod
    def from_file(cls, path: str | Path) -> "FirmwareReport":
        report_path = Path(path)
        with report_path.open("r", encoding="utf-8") as handle:
            payload = json.load(handle)
        return cls(path=report_path, payload=payload)

    @property
    def input_file(self) -> str:
        return str(self.payload.get("input_file", ""))

    @property
    def generated_at(self) -> str:
        return str(self.payload.get("generated_at", ""))

    @property
    def format_hints(self) -> list[str]:
        return [str(item) for item in self.payload.get("format_hints", [])]

    @property
    def memory_regions(self) -> list[dict[str, Any]]:
        return self.payload.get("memory_regions", [])

    @property
    def warnings(self) -> list[str]:
        return [str(item) for item in self.payload.get("warnings", [])]

    @property
    def stack_usage(self) -> dict[str, Any]:
        return self.payload.get("stack_usage", {})

    @property
    def linker_name(self) -> str:
        return str(self.payload.get("linker_name", ""))

    @property
    def linker_format(self) -> str:
        return str(self.payload.get("linker_format", ""))

    @property
    def linker_content(self) -> str:
        return str(self.payload.get("linker_content", ""))

    @property
    def linker_regions(self) -> list[dict[str, Any]]:
        return self.payload.get("linker_regions", [])

    @property
    def linker_extras(self) -> dict[str, Any]:
        return self.payload.get("linker_extras", {})

    @property
    def stats(self) -> dict[str, Any]:
        return self.payload.get("stats", {})

    @property
    def contributions(self) -> list[Contribution]:
        return [Contribution.from_dict(item) for item in self.payload.get("contributions", [])]

    def contributions_for_section(self, section_name: str) -> list[Contribution]:
        return [
            contribution
            for contribution in self.contributions
            if contribution.section == section_name
        ]

    def section_totals(self) -> dict[str, int]:
        totals: dict[str, int] = {}
        for entry in self.stats.get("by_section", []):
            name = str(entry.get("name", ""))
            totals[name] = int(entry.get("total", 0) or 0)
        return totals

    def total_memory_used(self) -> int:
        return sum(int(region.get("used", 0) or 0) for region in self.memory_regions)

    def total_memory_capacity(self) -> int:
        return sum(int(region.get("length", 0) or 0) for region in self.memory_regions)

    def summary(self) -> dict[str, Any]:
        return {
            "path": str(self.path),
            "input_file": self.input_file,
            "generated_at": self.generated_at,
            "memory_regions": self.memory_regions,
            "total_memory_used": self.total_memory_used(),
            "total_memory_capacity": self.total_memory_capacity(),
            "contribution_count": len(self.contributions),
            "section_totals": self.section_totals(),
            "warnings": self.warnings,
        }


def load_report(path: str | Path = DEFAULT_REPORT_PATH) -> FirmwareReport:
    """Load and validate a firmware report JSON file."""
    return FirmwareReport.from_file(path)


def _format_memory_regions(report: FirmwareReport) -> str:
    if not report.memory_regions:
        return "No memory regions found."

    lines: list[str] = []
    for region in report.memory_regions:
        name = region.get("name", "unknown")
        origin = region.get("origin", 0)
        length = region.get("length", 0)
        used = region.get("used", 0)
        lines.append(f"- {name}: origin=0x{origin:x}, length={length}, used={used}")
    return "\n".join(lines)

def _sum_by_type_and_component(report: FirmwareReport, ct: ContributionType, cc: ContributionComponent) -> int:

    mem_sum = 0
    for contr in report.contributions:
        if contr.kind == ct:
            if contr.component == cc:
                mem_sum = mem_sum + int(contr.size)

    return mem_sum

def _list_by_type_and_component(report: FirmwareReport, ct: ContributionType, cc: ContributionComponent) -> None:
    for contr in report.contributions:
        if contr.kind == ct and contr.component == cc:
            print(f"{contr.kind.value}, {contr.component.value}: {contr.symbol}, {contr.size}, {contr.source}")

def _get_contribution_type_total(report: FirmwareReport, section: str) -> int:
    ret = -1
    for contr in report.contributions:
        if contr.section == section and contr.source == "<section total>":
            ret = contr.size
            break
    return ret

def _get_modulesize_by_component(report: FirmwareReport, cc: ContributionComponent) -> dict[str, int]:
    ret = {}

    for contr in report.contributions:
        if contr.kind == ContributionType.CODE and contr.component == cc:
            module_code_size = 0
            if contr.source in ret:
                module_code_size = ret[contr.source]
            module_code_size += contr.size
            ret[contr.source] = module_code_size

    return ret


